/**
 * Writes lib/domain/icons.ts from the Lucide icon set (ISC license, https://lucide.dev).
 *
 *   npx -y lucide-static@<version> is not run here. Download the package yourself and pass the folder:
 *   npm pack lucide-static@<version> && tar xzf lucide-static-<version>.tgz && npx tsx scripts/icons.ts package
 *
 * A small curated set, named by what the icon means on a slide (risk, growth, delivery), not by how it looks. The model
 * picks by meaning, and the set stays small on purpose: an icon carries a meaning or it is decoration (Mayer, coherence).
 * The result is committed, so the build needs no network and no dependency.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/** Meaning on the slide -> file name in lucide-static/icons. */
const SET: Record<string, string> = {
  risk: "triangle-alert",
  security: "shield-check",
  lock: "lock",
  time: "clock",
  people: "users",
  person: "user",
  goal: "target",
  growth: "trending-up",
  decline: "trending-down",
  chart: "chart-column",
  money: "coins",
  global: "globe",
  speed: "zap",
  done: "circle-check",
  fail: "circle-x",
  layers: "layers",
  settings: "settings",
  data: "database",
  cloud: "cloud",
  delivery: "truck",
  company: "building-2",
  document: "file-text",
  search: "search",
  mail: "mail",
  launch: "rocket",
  milestone: "flag",
  link: "link",
  balance: "scale",
  partnership: "handshake",
  idea: "lightbulb",
  package: "package",
  route: "route",
};

const dir = resolve(process.argv[2] ?? "");
if (!process.argv[2]) throw new Error("Pass the unpacked lucide-static folder");
const version = (JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as { version: string }).version;

const entries = Object.entries(SET).map(([name, file]) => {
  const svg = readFileSync(join(dir, "icons", `${file}.svg`), "utf8");
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>[\s\S]*$/, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  if (!/^(?:<(?:path|rect|circle|line|polyline|polygon|ellipse)\b[^<>]*\/>)+$/.test(inner)) throw new Error(`${file}: unexpected markup ${inner.slice(0, 80)}`);
  return `  ${name}: ${JSON.stringify(inner)},`;
});

writeFileSync(
  resolve(import.meta.dirname, "../lib/domain/icons.ts"),
  `/**
 * Icons: a small curated set from Lucide ${version} (https://lucide.dev).
 * Copyright (c) 2026 Lucide Icons and Contributors. ISC license, the full notice (and the MIT notice for the icons derived
 * from Feather) is in docs/THIRD_PARTY.md, which ships in the npm package.
 * Generated by scripts/icons.ts. Do not edit. Named by what the icon means on a slide. 24x24, drawn with a stroke.
 */
export const ICON_SHAPES = {
${entries.join("\n")}
} as const;

export const ICON_NAMES = Object.keys(ICON_SHAPES) as [keyof typeof ICON_SHAPES, ...(keyof typeof ICON_SHAPES)[]];
export type IconName = (typeof ICON_NAMES)[number];

export const ICON_STROKE = 2;
`,
);
console.log(`${entries.length} icons from lucide-static ${version}`);
