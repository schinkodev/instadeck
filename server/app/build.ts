/**
 * Builds the MCP App: view.html with the embed mode CSS and the bundle of view.ts (esbuild, IIFE, no CDN).
 * The result is a module with one string, the server returns it as the resource ui://instadeck/deck.html.
 */
import { readFileSync } from "node:fs";
import { buildSync } from "esbuild";
import { MODE_CSS } from "@/lib/engine";

export function buildView(): string {
  const js = buildSync({
    entryPoints: ["server/app/view.ts"],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    logLevel: "warning",
  }).outputFiles[0]!.text;
  const html = readFileSync("server/app/view.html", "utf8")
    .replace("/*EMBED_CSS*/", () => MODE_CSS.embed)
    // The script must not close its own <script> tag.
    .replace("/*VIEW_JS*/", () => js.replace(/<\/script/gi, "<\\/script"));
  return `// Generated by npm run gen from server/app/view.html and view.ts. Do not edit.\nexport const VIEW_HTML = ${JSON.stringify(html)};\n`;
}
