import { DESIGN_PRINCIPLES, LAYER_NAMES, MOTION_PRINCIPLES, STORYTELLING_PRINCIPLES, isCovered, type Enforced } from "@/lib/domain";

const cell = (s: string) => s.replace(/\|/g, "/");

function table(rows: readonly (Enforced & { id: string; name: string; author: string })[]): string {
  const head = "| Principle | Author | Enforced by | Gap |\n|---|---|---|---|\n";
  const body = rows
    .map((p) => {
      const by = p.enforced.length ? p.enforced.map((e) => `${e.layer} ${LAYER_NAMES[e.layer]}: ${cell(e.by)}`).join("<br>") : "nothing";
      return `| ${cell(p.name)} | ${cell(p.author)} | ${by} | ${p.gap ? cell(p.gap) : ""} |`;
    })
    .join("\n");
  return head + body;
}

export function auditMarkdown(): string {
  const covered = (ps: readonly Enforced[]) => ps.filter(isCovered).length;
  return `# Principles audit

Generated by \`npm run gen\` from \`lib/domain/principles\`. Do not edit by hand. See V008.

Layers: 1 schema (a bad state cannot be written), 2 tokens (the renderer or derivation decides), 3 lint (validation or browser measurement reports it), 4 critique (judgement of the model only).

A principle is covered when layers 1 to 3 enforce it. A principle with critique only is a judgement call that no measurement captures today. A principle enforced by nothing names its gap.

## Design principles (${covered(DESIGN_PRINCIPLES)} of ${DESIGN_PRINCIPLES.length} covered)

${table(DESIGN_PRINCIPLES)}

## Storytelling principles (${covered(STORYTELLING_PRINCIPLES)} of ${STORYTELLING_PRINCIPLES.length} covered)

${table(STORYTELLING_PRINCIPLES)}

## Motion principles

Motion principles name the validation rule that measures them (\`measured\`) and are audited by the motion tests.

${MOTION_PRINCIPLES.map((p) => `- ${p.name} (${p.author}): ${p.measured ?? "not measured"}`).join("\n")}
`;
}
